/**
 * seolyticize types: the client's live goal and event names as a .d.ts that
 * fills @seolyticize/web's Goals interface, so track("Sign up") fails tsc
 * when the goal is "Signup".
 */
type Caller = { call(tool: string, input: unknown): Promise<unknown> };

/** The event names: event goals (wildcard ones say nothing exact) and the events the site already sends. */
export async function goalNames(sdk: Caller, clientId: string): Promise<string[]> {
  const [goals, sent] = (await Promise.all([
    sdk.call("list_goals", { clientId }),
    sdk.call("list_conversion_goals", { clientId }),
  ])) as [
    { goals: Array<{ kind: string; match: string }> },
    { goals: Array<{ name: string }> },
  ];
  const names = [
    ...goals.goals.filter((goal) => goal.kind === "event").map((goal) => goal.match),
    ...sent.goals.map((goal) => goal.name),
  ].filter((name) => name && !name.includes("*"));
  return [...new Set(names)].toSorted();
}

export function renderGoalTypes(names: string[], clientId: string): string {
  const props =
    "{ value?: number; currency?: string; orderId?: string | number; [prop: string]: string | number | boolean | undefined }";
  return [
    `// Generated by \`seolyticize types --client ${clientId}\` from the live goals. Do not edit; run it again.`,
    'import "@seolyticize/web";',
    "",
    'declare module "@seolyticize/web" {',
    "  interface Goals {",
    ...names.map((name) => `    ${JSON.stringify(name)}: ${props};`),
    "  }",
    "}",
    "",
  ].join("\n");
}
